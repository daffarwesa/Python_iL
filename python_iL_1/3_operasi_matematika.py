"""
3. Operasi Matematika Sederhana
"""

angka_a = 20
angka_b = 6

print("=== 3. Operasi Matematika Sederhana ===")
print(f"{angka_a} + {angka_b} =", angka_a + angka_b)
print(f"{angka_a} - {angka_b} =", angka_a - angka_b)
print(f"{angka_a} * {angka_b} =", angka_a * angka_b)
print(f"{angka_a} / {angka_b} =", angka_a / angka_b)
print(f"{angka_a} // {angka_b} =", angka_a // angka_b)
print(f"{angka_a} % {angka_b} =", angka_a % angka_b)
