"""
2. Manipulasi String
"""

nama_kota = "Batam"
kata_depan = "Selamat datang di"
kalimat_gabungan = kata_depan + " " + nama_kota

print("=== 2. Manipulasi String ===")
print("Gabungan string      :", kalimat_gabungan)
print("Panjang string        :", len(kalimat_gabungan), "karakter")
print("Huruf besar (upper)   :", kalimat_gabungan.upper())
print("Huruf kecil (lower)   :", kalimat_gabungan.lower())
